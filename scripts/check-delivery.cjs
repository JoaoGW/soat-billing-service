const assert = require('node:assert/strict');
const fs = require('node:fs');
const yaml = require('js-yaml');
const workflow = yaml.load(fs.readFileSync('.github/workflows/ci.yml', 'utf8'));
const publish = workflow.jobs.publish;
const deploy = workflow.jobs.deploy_hml;
assert.deepEqual(publish.needs, ['quality', 'integration']);
assert.match(publish.if, /github\.event_name == 'push'/);
assert.match(publish.if, /refs\/heads\/development/);
assert.match(publish.if, /vars\.HML_DEPLOY_ENABLED == 'true'/);
assert.equal(deploy.needs, 'publish');
assert.equal(deploy.environment, 'hml');
assert.equal(deploy.permissions['id-token'], 'write');
const imageSteps = publish.steps.filter(step => step.uses === 'docker/build-push-action@v6');
assert.equal(imageSteps.length, 2);
for (const step of imageSteps) assert.match(step.with.tags, /\$\{\{ github\.sha \}\}/);
assert.deepEqual(imageSteps.map(step => step.with.target), ['runtime', 'migration']);
const migrationIndex = deploy.steps.findIndex(step => step.name === 'Migrar banco próprio antes do rollout');
const deployIndex = deploy.steps.findIndex(step => step.name === 'Aplicar exatamente a imagem do SHA aprovado');
assert.ok(migrationIndex >= 0 && deployIndex > migrationIndex);
assert.match(deploy.steps[migrationIndex].run, /soat-billing-migration/);
assert.match(deploy.steps[deployIndex].run, /IMAGE_SHA/);
console.log('Trava, CI, imagens por SHA e migração verificados.');
